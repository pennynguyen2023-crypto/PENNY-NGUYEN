def char_weight(text):
    return len(text.replace(" ", ""))

def main():
    weights = {n: char_weight(t) for n, t in SCENE_TEXT.items()}
    total_weight = sum(weights.values())

    timings = {}
    t = 0.0
    for n in sorted(SCENE_TEXT.keys()):
        dur = TOTAL_DURATION * (weights[n] / total_weight)
        start = t
        end = t + dur
        timings[n] = (round(start, 2), round(end, 2), round(dur, 2))
        t = end

    return timings

if __name__ == "__main__":
    timings = main()
    import json
    with open("scene_timings.json", "w") as f:
        json.dump({str(k): v for k, v in timings.items()}, f, ensure_ascii=False, indent=2)
    for n in sorted(timings.keys()):
        s, e, d = timings[n]
        print(f"Scene {n}: {s:.2f}s - {e:.2f}s (dur {d:.2f}s)")
